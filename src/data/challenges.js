// ─── HELPERS ──────────────────────────────────────────────────────────────────

export function getCurrentMonthChallenge() {
  const month = new Date().getMonth() + 1;
  return MONTHLY_CHALLENGES.find(c => c.month === month) || null;
}

export function getCurrentSeasonChallenge() {
  const month = new Date().getMonth() + 1;
  return SEASONAL_CHALLENGES.find(c => c.months.includes(month)) || null;
}

export function getActiveHolidayChallenges() {
  const now = new Date();
  const month = now.getMonth() + 1;
  const day = now.getDate();
  return HOLIDAY_CHALLENGES.filter(c => {
    const afterStart = month > c.windowStart.month || (month === c.windowStart.month && day >= c.windowStart.day);
    const beforeEnd = month < c.windowEnd.month || (month === c.windowEnd.month && day <= c.windowEnd.day);
    return afterStart && beforeEnd;
  });
}

export function getChallengeProgress(challenge, completedTaskIds = []) {
  const tasks = challenge.tasks || [];
  const completed = tasks.filter(t => completedTaskIds.includes(t.id)).length;
  return { completed, total: tasks.length, percent: tasks.length > 0 ? completed / tasks.length : 0 };
}

export function getAllChallengeBadges() {
  const monthly = MONTHLY_CHALLENGES.map(c => c.badge);
  const seasonal = SEASONAL_CHALLENGES.map(c => c.badge);
  const holiday = HOLIDAY_CHALLENGES.map(c => c.badge);
  const milestone = MILESTONE_CHALLENGES.map(c => c.badge);
  return [...monthly, ...seasonal, ...holiday, ...milestone];
}
